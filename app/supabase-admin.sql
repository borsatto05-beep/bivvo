-- BIVVO — Área Administrativa / Analytics (execute uma vez no Supabase SQL Editor)
create table if not exists public.admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'super_admin' check (role in ('super_admin','support','finance','analytics')),
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null check (char_length(visitor_id) between 8 and 80),
  session_id text not null check (char_length(session_id) between 8 and 80),
  user_id uuid references auth.users(id) on delete set null,
  event text not null check (event ~ '^[a-z0-9_]{2,50}$'),
  route text,
  source text,
  medium text,
  campaign text,
  device text,
  browser text,
  os text,
  created_at timestamptz not null default now()
);
create index if not exists analytics_events_created_idx on public.analytics_events(created_at desc);
create index if not exists analytics_events_event_idx on public.analytics_events(event, created_at desc);
create index if not exists analytics_events_visitor_idx on public.analytics_events(visitor_id, created_at desc);

create table if not exists public.billing_payments (
  id bigint generated by default as identity primary key,
  mp_payment_id text not null unique,
  mp_subscription_id text,
  user_id uuid references auth.users(id) on delete set null,
  plan text check (plan in ('plus','pro','couple','capital','entrepreneur','family')),
  status text not null,
  amount numeric(10,2),
  currency text default 'BRL',
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists billing_payments_paid_idx on public.billing_payments(status, paid_at desc);
create index if not exists billing_payments_user_idx on public.billing_payments(user_id, paid_at desc);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  admin_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_audit_created_idx on public.admin_audit_logs(created_at desc);

create table if not exists public.system_events (
  id bigint generated by default as identity primary key,
  service text not null,
  event text not null,
  ok boolean not null default true,
  message text,
  created_at timestamptz not null default now()
);
create index if not exists system_events_service_idx on public.system_events(service, created_at desc);

alter table public.admin_roles enable row level security;
alter table public.analytics_events enable row level security;
alter table public.billing_payments enable row level security;
alter table public.admin_audit_logs enable row level security;
alter table public.system_events enable row level security;
alter table public.admin_roles force row level security;
alter table public.analytics_events force row level security;
alter table public.billing_payments force row level security;
alter table public.admin_audit_logs force row level security;
alter table public.system_events force row level security;

revoke all on public.admin_roles, public.analytics_events, public.billing_payments, public.admin_audit_logs, public.system_events from anon, authenticated;

