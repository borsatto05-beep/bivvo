-- BIVVO 10.5 — Fundação de monetização. Execute uma vez no Supabase SQL Editor.
-- O app continua funcionando sem isto (todos ficam no plano Grátis e a leitura de comprovante fica indisponível).
-- Tudo que concede plano, conta uso ou registra indicação é escrito SÓ pelo servidor (service role).

-- 1) Planos ativos (assinatura futura, teste grátis, recompensa de indicação)
create table if not exists public.entitlements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan text not null check (plan in ('plus','pro','couple','capital','entrepreneur','family')),
  source text not null check (char_length(source) between 2 and 64),   -- ex.: 'trial', 'referral_welcome', 'referral_reward_1', 'stripe'
  starts_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (user_id, source)
);
create index if not exists entitlements_user_idx on public.entitlements(user_id, expires_at);

-- 2) Uso mensal de recursos com custo (leitura de comprovante, IA)
create table if not exists public.usage_counters (
  user_id uuid not null references auth.users(id) on delete cascade,
  feature text not null check (feature in ('scan','ai')),
  period text not null check (period ~ '^\d{4}-\d{2}$'),
  used integer not null default 0 check (used >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, feature, period)
);

-- 3) Métricas de produto (sem valores, descrições ou dados financeiros)
create table if not exists public.product_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event text not null check (event ~ '^[a-z_]{2,40}$'),
  props jsonb not null default '{}'::jsonb check (pg_column_size(props) < 1000),
  created_at timestamptz not null default now()
);
create index if not exists product_events_event_idx on public.product_events(event, created_at);

-- 4) Indicações
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referrer uuid not null references auth.users(id) on delete cascade,
  referred_user uuid not null unique references auth.users(id) on delete cascade,
  status text not null default 'activated' check (status in ('pending','activated','rejected')),
  reward_status text not null default 'none' check (reward_status in ('none','granted','capped')),
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  check (referrer <> referred_user)
);
create index if not exists referrals_referrer_idx on public.referrals(referrer, status);

alter table public.entitlements enable row level security;   alter table public.entitlements force row level security;
alter table public.usage_counters enable row level security; alter table public.usage_counters force row level security;
alter table public.product_events enable row level security; alter table public.product_events force row level security;
alter table public.referrals enable row level security;      alter table public.referrals force row level security;

drop policy if exists "ent_select_own" on public.entitlements;
create policy "ent_select_own" on public.entitlements for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "usage_select_own" on public.usage_counters;
create policy "usage_select_own" on public.usage_counters for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "events_insert_own_product" on public.product_events;
create policy "events_insert_own_product" on public.product_events for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "ref_select_referrer" on public.referrals;
create policy "ref_select_referrer" on public.referrals for select to authenticated using ((select auth.uid()) = referrer);

revoke all on public.entitlements, public.usage_counters, public.product_events, public.referrals from anon;
revoke all on public.entitlements, public.usage_counters, public.product_events, public.referrals from authenticated;
grant select on public.entitlements to authenticated;
grant select on public.usage_counters to authenticated;
grant insert on public.product_events to authenticated;
grant select on public.referrals to authenticated;

-- Consome 1 uso de forma atômica. Retorna o total usado, ou -1 se passaria do limite.
create or replace function public.bivvo_consume_usage(p_user uuid, p_feature text, p_period text, p_limit integer)
returns integer language plpgsql security definer set search_path = public as $$
declare v integer;
begin
  insert into public.usage_counters(user_id, feature, period, used) values (p_user, p_feature, p_period, 0)
  on conflict (user_id, feature, period) do nothing;
  update public.usage_counters set used = used + 1, updated_at = now()
   where user_id = p_user and feature = p_feature and period = p_period and used < p_limit
  returning used into v;
  return coalesce(v, -1);
end; $$;
-- Devolve o uso quando a leitura falha (o usuário não perde cota por erro nosso).
create or replace function public.bivvo_refund_usage(p_user uuid, p_feature text, p_period text)
returns void language sql security definer set search_path = public as $$
  update public.usage_counters set used = greatest(0, used - 1), updated_at = now()
   where user_id = p_user and feature = p_feature and period = p_period;
$$;
-- Código de convite = 8 primeiros caracteres de sha256('bivvo:' || id). Mesmo cálculo do app.
create or replace function public.bivvo_referrer_by_code(p_code text)
returns uuid language sql security definer set search_path = public, extensions as $$
  select id from auth.users
   where p_code ~ '^[a-f0-9]{8}$' and substr(encode(extensions.digest('bivvo:' || id::text, 'sha256'), 'hex'), 1, 8) = p_code
   order by created_at asc limit 1;
$$;
revoke all on function public.bivvo_consume_usage(uuid,text,text,integer) from public, anon, authenticated;
revoke all on function public.bivvo_refund_usage(uuid,text,text) from public, anon, authenticated;
revoke all on function public.bivvo_referrer_by_code(text) from public, anon, authenticated;
grant execute on function public.bivvo_consume_usage(uuid,text,text,integer) to service_role;
grant execute on function public.bivvo_refund_usage(uuid,text,text) to service_role;
grant execute on function public.bivvo_referrer_by_code(text) to service_role;

-- 5) Assinaturas Mercado Pago (V10.5 MP)
create table if not exists public.billing_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan text not null check (plan in ('plus','pro','couple','capital','entrepreneur','family')),
  mp_subscription_id text not null unique,
  status text not null default 'pending',
  amount numeric(10,2) not null check (amount > 0),
  currency text not null default 'BRL' check (currency = 'BRL'),
  next_payment_date timestamptz,
  last_sync_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists billing_subscriptions_user_idx on public.billing_subscriptions(user_id, created_at desc);
alter table public.billing_subscriptions enable row level security;
alter table public.billing_subscriptions force row level security;
drop policy if exists "billing_select_own" on public.billing_subscriptions;
create policy "billing_select_own" on public.billing_subscriptions for select to authenticated using ((select auth.uid()) = user_id);
revoke all on public.billing_subscriptions from anon;
revoke all on public.billing_subscriptions from authenticated;
grant select on public.billing_subscriptions to authenticated;
