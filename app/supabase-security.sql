-- Bivvo v4: rate limiting persistente para Netlify Functions.
create table if not exists public.api_rate_limits (
  bucket_key text primary key,
  window_start timestamptz not null default now(),
  request_count integer not null default 0
);
alter table public.api_rate_limits enable row level security;
revoke all on table public.api_rate_limits from anon, authenticated;

create or replace function public.bivvo_rate_limit(p_key text, p_limit integer default 30, p_window_seconds integer default 60)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare r public.api_rate_limits%rowtype;
begin
  if p_key is null or length(p_key) > 180 or p_limit < 1 or p_window_seconds < 1 then return false; end if;
  insert into public.api_rate_limits(bucket_key, window_start, request_count)
  values (p_key, now(), 1)
  on conflict (bucket_key) do update set
    window_start = case when public.api_rate_limits.window_start <= now() - make_interval(secs => p_window_seconds) then now() else public.api_rate_limits.window_start end,
    request_count = case when public.api_rate_limits.window_start <= now() - make_interval(secs => p_window_seconds) then 1 else public.api_rate_limits.request_count + 1 end
  returning * into r;
  return r.request_count <= p_limit;
end;
$$;
revoke all on function public.bivvo_rate_limit(text,integer,integer) from public, anon, authenticated;
grant execute on function public.bivvo_rate_limit(text,integer,integer) to service_role;

-- V6: verificação server-side de MFA para operações destrutivas.
-- A função só pode ser chamada pelo service_role (Netlify Function).
create or replace function public.bivvo_user_has_verified_mfa(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from auth.mfa_factors
    where user_id = p_user_id
      and status = 'verified'
  );
$$;
revoke all on function public.bivvo_user_has_verified_mfa(uuid) from public, anon, authenticated;
grant execute on function public.bivvo_user_has_verified_mfa(uuid) to service_role;
