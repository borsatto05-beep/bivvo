import assert from 'node:assert/strict';
globalThis.sessionStorage={getItem:()=>null,setItem(){},removeItem(){}};
globalThis.localStorage={getItem:()=>null,setItem(){},removeItem(){},key(){return null},length:0};
const store=await import('../js/store.js');
const {setPaidAccess}=await import('../js/paid-access.js');
store.load({profile:{onboarded:true,name:'Dono'},transactions:[]});
assert(store.categories('expense').includes('Moradia'));
assert(!store.categories('expense').includes('Fornecedores'));
assert(store.categories('income').includes('Salário'));
setPaidAccess('entrepreneur');
store.switchFinanceProfile('company');
const exp=store.categories('expense'),inc=store.categories('income');
assert(exp.includes('Fornecedores'));
assert(exp.includes('Folha de pagamento'));
assert(exp.includes('Pró-labore'));
assert(exp.includes('Impostos e tributos'));
assert(exp.includes('Marketing e anúncios'));
assert(!exp.includes('Moradia'));
assert(!exp.includes('Pets'));
assert(inc.includes('Vendas de produtos'));
assert(inc.includes('Prestação de serviços'));
assert(inc.includes('Recebimentos de clientes'));
assert(!inc.includes('Salário'));
assert.equal(store.autoCategory('DAS MEI outubro','expense'),'Impostos e tributos');
assert.equal(store.autoCategory('Meta Ads campanha','expense'),'Marketing e anúncios');
assert.equal(store.autoCategory('Pagamento fornecedor ABC','expense'),'Fornecedores');
assert.equal(store.autoCategory('Venda de produto pedido 123','income'),'Vendas de produtos');
assert.equal(store.autoCategory('Recebimento cliente XPTO','income'),'Recebimentos de clientes');
store.switchFinanceProfile('personal');
assert(store.categories('expense').includes('Moradia'));
assert(!store.categories('expense').includes('Folha de pagamento'));
console.log('Company mode uses business-only categories and auto-categorization without polluting personal mode.');
