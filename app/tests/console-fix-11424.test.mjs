import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(new URL('..', import.meta.url).pathname);
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let pass=0, fail=0;
const t=(name,ok)=>{if(ok){console.log('✓',name);pass++;}else{console.error('✗',name);fail++;}};
const loans=read('js/views/loans.js');
const main=read('js/main.js');
const sw=read('sw.js');
const util=read('js/util.js');
const netlify=read('netlify.toml');
t('loans.js sem optional chaining', !loans.includes('?.'));
t('loans.js sem nullish coalescing', !loans.includes('??'));
t('loanDetail foi reescrito em blocos legíveis', /const kpis=h\('div\.loan-detail-kpis'/.test(loans) && /const history=timeline\(/.test(loans));
t('edição de pagamento preservada', /editLoanPayment\(l,p\)/.test(loans));
t('exclusão de pagamento preservada', /deleteLoanPayment\(l,p,sh\)/.test(loans));
t('receber só juros preservado', /interestOnly:true/.test(loans));
t('main importa módulo loans com cache-bust 11.42.6', /\.\/views\/loans\.js\?v=11\.42\.6/.test(main));
t('versão pública 11.84.0', /VERSION\s*=\s*'11\.84\.0'/.test(util));
t('service worker 11.84.0', /bivvo-v11-84-0/.test(sw));
t('CSP inclui hash de script observado no srcdoc', netlify.includes("'sha256-mTJ4cJaTm2Gw995gXePZdVfEYYgbh6FZu1bwcNE7Q1Y='"));
t('CSP inclui hash de style observado no srcdoc', netlify.includes("'sha256-ti+3uTLCm2PTeuT2PIaIt1HWU52Pn4+bliwh6wz9b+s='"));
t('CSP não liberou unsafe-inline em script-src principal', !/script-src [^;]*'unsafe-inline'/.test(netlify));
console.log(`\n${pass}/${pass+fail} testes passaram`);
if(fail) process.exit(1);
