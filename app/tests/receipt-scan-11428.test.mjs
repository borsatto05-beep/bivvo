import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = path.resolve(new URL('..', import.meta.url).pathname);
const scanFn = require(path.join(root, 'netlify/functions/scan-receipt.js'));
const T = scanFn._test;
let pass=0, fail=0;
const t=(name,ok)=>{if(ok){console.log('✓',name);pass++;}else{console.error('✗',name);fail++;}};

const base={is_receipt:true,receipt_type:'Cupom fiscal',value_label:'TOTAL',value_text:'R$ 83,70',value:83.7,date:'2026-10-06',merchant:'Mercado Bom',description:'Compra',payment_method:'PIX',installments:null,category_hint:'Mercado',confidence:.88,confidence_value:.94,confidence_merchant:.92,confidence_date:.9,confidence_payment_method:.8,confidence_category:.9};
const a=T.normalizeRaw(base);
const b=T.normalizeRaw({...base,confidence:.91,confidence_value:.97});
const merged=T.mergeReads(a,b,{issues:[],autoCrop:true,perspectiveCorrected:true},{detected:true,kind:'nfce_url'});
t('mantém valor consensual', merged.value===83.7);
t('preserva tipo de comprovante', merged.receiptType==='Cupom fiscal');
t('eleva confiança de valor quando duas leituras concordam', merged.fieldConfidence.value>.94);
t('retorna confiança por campo', merged.fieldConfidence.merchant>.8 && merged.fieldConfidence.date>.8);
t('não pede revisão de valor com alta confiança', !merged.reviewFields.includes('value'));
t('sinaliza correção de perspectiva', merged.scanMeta.perspectiveCorrected===true);
t('sinaliza QR detectado', merged.scanMeta.qrDetected===true);
const low=T.normalizeRaw({...base,merchant:null,date:null,payment_method:null,category_hint:null,confidence:.5,confidence_value:.55,confidence_merchant:0,confidence_date:0,confidence_payment_method:0,confidence_category:0});
const lowMerged=T.mergeReads(low,null,{issues:['possibly_blurry']},{detected:false});
t('campos incertos entram em reviewFields', ['value','merchant','date','method','category'].every(x=>lowMerged.reviewFields.includes(x)));
t('problema de nitidez é preservado', lowMerged.qualityIssues.includes('possibly_blurry'));
const conflict=T.normalizeRaw({...base,value_text:'R$ 18,90',value:18.9,confidence_value:.85});
const cm=T.mergeReads(a,conflict,{issues:[]},{detected:false});
t('conflito de valores gera opções', cm.valueOptions.length===2);
t('conflito força revisão do valor', cm.reviewFields.includes('value') && cm.mismatch===true);

const client=fs.readFileSync(path.join(root,'js/scan.js'),'utf8');
const confirm=fs.readFileSync(path.join(root,'js/views/scanconfirm.js'),'utf8');
const server=fs.readFileSync(path.join(root,'netlify/functions/scan-receipt.js'),'utf8');
const quick=fs.readFileSync(path.join(root,'js/quickcapture.js'),'utf8');
t('scanner usa getUserMedia com fallback', /getUserMedia/.test(client) && /return pickImage\(\)/.test(client));
t('scanner tenta ImageCapture para foto em alta resolução', /ImageCapture/.test(client) && /takePhoto/.test(client));
t('scanner tem auto-disparo por frames bons', /goodFrames>=5/.test(client));
t('scanner avalia movimento, foco, luz e reflexo', /frameMotion/.test(client) && /possibly_blurry/.test(client) && /too_dark/.test(client) && /glare/.test(client));
t('scanner detecta contorno e corrige perspectiva', /detectPaperQuad/.test(client) && /warpPaper/.test(client) && /perspectiveCoefficients/.test(client));
t('scanner cria terceira variante para zona do total', /total_detail/.test(client) && /totalDetail/.test(client));
t('scanner tenta QR Code nativo sem biblioteca pesada', /BarcodeDetector/.test(client) && /qr_code/.test(client));
t('servidor aceita múltiplas versões da mesma foto', /slice\(0,(?:3|5)\)/.test(server));
t('servidor usa confiança por campo', /confidence_value/.test(server) && /reviewFields/.test(server));
t('quickcapture chama scanner inteligente', /captureSmartReceipt/.test(quick));
console.log(`\n${pass}/${pass+fail} testes Scan 11.42.8 passaram`);
if(fail) process.exit(1);
