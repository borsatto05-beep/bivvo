import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),T=require('../netlify/functions/scan-receipt.js')._test;
const mk=(value,extra={})=>T.normalizeRaw({is_receipt:true,value,value_text:`R$ ${value},00`,confidence:.95,confidence_value:.96,merchant:'Synthetic Store',confidence_merchant:.9,evidence_value:`TOTAL ${value}`,...extra});
assert(Number.isNaN(T.toNumber(null)));
assert.equal(T.normalizeRaw({is_receipt:true,value:20,confidence:.9}).value,20);
assert.equal(T.normalizeRaw({is_receipt:true,value:null,value_text:'20,00',confidence:.9},{allowRecovery:false}).value,null);
const zero=mk(20,{confidence_value:0,confidence_merchant:0});
assert.equal(zero.fieldConfidence.value,0);assert.equal(zero.fieldConfidence.merchant,0);
assert.equal(T.normalizeRaw({is_receipt:'false',date:'2026-02-31'}).isReceipt,false);
assert.equal(T.normalizeRaw({is_receipt:true,date:'2026-02-31'}).date,null);
assert.equal(T.normalizeRaw({is_receipt:true,date:'2026-02-28'}).date,'2026-02-28');
const a=mk(20),b=mk(30),judge=T.normalizeRaw({is_receipt:true,value:null,confidence:.2});
let merged=T.mergeReads(a,b,{},null,judge);
assert.equal(merged.value,null);assert.equal(merged.valueText,null);assert(merged.reviewFields.includes('value'));
merged=T.mergeReads(mk(20,{confidence_value:.6}),null,{},T.sanitizeQr({detected:true,kind:'pix_qr',amount:999}));
assert.equal(merged.value,20);assert.equal(merged.scanMeta.qrAmountUsed,false);
assert(merged.valueOptions.includes(999));
assert(T.canUseSingleRead(a,{issues:[]},null));
assert(!T.canUseSingleRead(zero,{issues:[]},null));
assert(!T.canUseSingleRead(a,{issues:['glare']},null));
assert(!T.canUseSingleRead(a,{issues:[]},{amount:999}));
console.log('Scanner: zero confidence, invalid dates/types, abstention, untrusted QR and adaptive gating passed.');
