import assert from 'node:assert/strict';
import {mergePayload} from '../js/sync-merge.js';
globalThis.sessionStorage={getItem(){return null;},setItem(){},removeItem(){}};
const store=await import('../js/store.js');
const base={transactions:[{id:'a',value:20,desc:'Old',cat:'Outros'}],profile:{name:'Person',onboarded:true}};
let m=mergePayload({transactions:[],profile:base.profile},base,new Set(),base);
assert.equal(m.transactions.length,0);assert(m.deletedRecords.a);
m=mergePayload({...base,transactions:[{...base.transactions[0],value:40}]},{...base,profile:{...base.profile,name:'Edited'}},new Set(),base);
assert.equal(m.transactions[0].value,40);assert.equal(m.profile.name,'Edited');
m=mergePayload({...base,transactions:[{...base.transactions[0],value:40}]},{...base,transactions:[{...base.transactions[0],desc:'New'}]},new Set(),base);
assert.equal(m.transactions[0].value,40);assert.equal(m.transactions[0].desc,'New');
m=mergePayload({...base,deletedRecords:{a:new Date().toISOString()}},base);
assert.equal(m.transactions.length,0);
store.load(base);
store.commit(s=>s.transactions=[]);
const snapshot=store.serialize();assert(snapshot.deletedRecords.a);assert(store.deletedIds().has('a'));
store.load(snapshot);assert(store.deletedIds().has('a'));
store.load({...base,deletedRecords:snapshot.deletedRecords});assert.equal(store.getState().transactions.length,0);
store.restoreRecords({transactions:base.transactions});assert.equal(store.getState().transactions.length,1);
assert.notEqual(store.getState().transactions[0].id,'a');assert(store.getState().deletedRecords.a);
store.load({installments:[],transactions:[]});
store.restoreRecords({installments:[{id:'group',total:10,parts:2}],transactions:[{id:'part',installmentId:'group',value:5}]});
assert.equal(store.getState().transactions[0].installmentId,store.getState().installments[0].id);
console.log('Sync: remote deletions, stale clients, concurrent edits, persistent markers and undo passed.');
