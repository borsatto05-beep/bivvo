import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(new URL('..', import.meta.url).pathname);
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let pass=0, fail=0;
function t(name,ok){ if(ok){console.log('✓',name);pass++;} else {console.error('✗',name);fail++;} }
const util=read('js/util.js');
const index=read('index.html');
const sw=read('sw.js');
const cloud=read('js/cloud.js');
const main=read('js/main.js');
t('VERSION pública = 11.85.0', /VERSION\s*=\s*'11\.85\.0'/.test(util));
t('index faz cache-bust do app.css', /app\.css\?v=11\.85\.0/.test(index));
t('index faz cache-bust do main.js', /js\/main\.js\?v=11\.85\.0/.test(index));
t('service worker usa cache 11.85.0', /bivvo-v11-85-0/.test(sw));
t('shell do SW aponta para assets 11.85.0', /app\.css\?v=11\.85\.0/.test(sw)&&/js\/main\.js\?v=11\.85\.0/.test(sw));
t('Supabase usa clientPromise compartilhada', /let client = null, clientPromise = null/.test(cloud)&&/if \(clientPromise\) return clientPromise/.test(cloud));
t('SW é registrado sem cache intermediário', /updateViaCache:\s*'none'/.test(main));
t('registro força conferência de atualização', /reg\.update\(\)/.test(main));
t('assistant mantém cache-bust de sua revisão', /views\/assistant\.js\?v=11\.84\.0/.test(main));
console.log(`\n${pass}/${pass+fail} testes passaram`);
if(fail) process.exit(1);
